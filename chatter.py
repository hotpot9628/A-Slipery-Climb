def pick(lang, avoid=None):
    lines = LINES.get(lang) or LINES["en"]
    if len(lines) == 1:
        return lines[0]
    for _ in range(6):
        line = lines[random.randrange(len(lines))]
        if line != avoid:
            return line
    return lines[random.randrange(len(lines))]
